    private void btnAgregarEmpleadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEmpleadoActionPerformed
        String nombre = lblNombreEmpleado.getText().trim();
        String cedula = lblCedulaEmpleado.getText().trim();
        String direccion = lblDireccionEmpleado.getText().trim();
        String nroEmpleado = lblNroEmpleado.getText().trim();

        if (nombre.isEmpty() || cedula.isEmpty() || direccion.isEmpty() || nroEmpleado.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Empleado existente = modelo.buscarEmpleadoPorCedula(cedula);
        if (existente != null) {
            JOptionPane.showMessageDialog(this, "Ya existe un empleado con esa cédula.", "Cédula duplicada", JOptionPane.ERROR_MESSAGE);
            return;
        }

        modelo.agregarEmpleado(new Empleado(nombre, cedula, direccion, nroEmpleado));
        btnVaciarEmpleadoActionPerformed(null);
        JOptionPane.showMessageDialog(this, "Empleado agregado con éxito.");

    }//GEN-LAST:event_btnAgregarEmpleadoActionPerformed

