    private void listaEmpleadosEmpleadoValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaEmpleadosEmpleadoValueChanged
        Empleado emp = (Empleado) listaEmpleadosEmpleado.getSelectedValue();
        if (emp == null) {
            return;
        }

        lblNombreEmpleado.setText(emp.getNombre());
        lblCedulaEmpleado.setText(emp.getCedula());
        lblDireccionEmpleado.setText(emp.getDireccion());
        lblNroEmpleado.setText(emp.getNumeroEmpleado());
    }//GEN-LAST:event_listaEmpleadosEmpleadoValueChanged

