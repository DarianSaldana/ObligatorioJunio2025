    private void btnCrearContratoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearContratoActionPerformed
        Cliente cliente = (Cliente) listaClientesContrato.getSelectedValue();
        Vehiculo vehiculo = (Vehiculo) listaVehiculosContrato.getSelectedValue();
        Empleado empleado = (Empleado) listaEmpleadosContrato.getSelectedValue();

        if (cliente == null || vehiculo == null || empleado == null || lblValorMensualContrato.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double valorMensual = Double.parseDouble(lblValorMensualContrato.getText());

            if (modelo.vehiculoYaContratado(vehiculo)) {
                JOptionPane.showMessageDialog(this, "Este vehículo ya está asociado a un contrato.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            Contrato contrato = new Contrato(cliente, vehiculo, empleado, valorMensual);
            modelo.agregarContrato(contrato);
            JOptionPane.showMessageDialog(this, "Contrato creado con éxito.");
            actualizarListaContratos();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un valor mensual válido.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCrearContratoActionPerformed

