    private void listaContratosExistentesValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaContratosExistentesValueChanged
        if (!evt.getValueIsAdjusting()) {
            Contrato contrato = (Contrato) listaContratosExistentes.getSelectedValue();
            if (contrato != null) {
                JPanel panel = new JPanel();
                panel.setLayout(new GridLayout(0, 1, 5, 5));

                panel.add(new JLabel("ID del Contrato: " + contrato.getId()));
                panel.add(new JLabel("Cliente: " + contrato.getCliente().getNombre()));
                panel.add(new JLabel("Cédula: " + contrato.getCliente().getCedula()));
                panel.add(new JLabel("Vehículo: " + contrato.getVehiculo().getMatricula()));
                panel.add(new JLabel("Marca: " + contrato.getVehiculo().getMarca()));
                panel.add(new JLabel("Empleado: " + contrato.getEmpleado().getNombre()));
                panel.add(new JLabel("Valor Mensual: $" + contrato.getValorMensual()));

                JOptionPane.showMessageDialog(this, panel, "Detalle del Contrato", JOptionPane.INFORMATION_MESSAGE);
            }
        }    }//GEN-LAST:event_listaContratosExistentesValueChanged

