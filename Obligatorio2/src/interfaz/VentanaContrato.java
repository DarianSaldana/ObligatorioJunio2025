    private void actualizarListaContratos() {
        DefaultListModel modeloLista = new DefaultListModel();
        for (Contrato contrato : modelo.getListaContratos()) {
            modeloLista.addElement(contrato);
        }
        listaContratosExistentes.setModel(modeloLista);
    }

    private void cargarListas() {
        // Clientes
        DefaultListModel modeloClientes = new DefaultListModel();
        for (Cliente c : modelo.getListaClientes()) {
            modeloClientes.addElement(c);
        }
        listaClientesContrato.setModel(modeloClientes);

        // Vehículos
        DefaultListModel modeloVehiculos = new DefaultListModel();
        for (Vehiculo v : modelo.getListaVehiculos()) {
            modeloVehiculos.addElement(v);
        }
        listaVehiculosContrato.setModel(modeloVehiculos);

        // Empleados
        DefaultListModel modeloEmpleados = new DefaultListModel();
        for (Empleado e : modelo.getListaEmpleados()) {
            modeloEmpleados.addElement(e);
        }
        listaEmpleadosContrato.setModel(modeloEmpleados);

        // Contratos existentes
        actualizarListaContratos();
    }

