    private void btnEntradaVehiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntradaVehiculoActionPerformed

        Vehiculo vehiculoSeleccionado = (Vehiculo) listaVehiculosEntrada.getSelectedValue();
        Empleado empleadoSeleccionado = (Empleado) listaEmpleadosEntrada.getSelectedValue();
        String fechaTexto = lblFechaEntrada.getText().trim();
        String horaTexto = lblHoraEntrada.getText().trim();
        String notas = txtAreaNotasEntrada.getText().trim();

        if (vehiculoSeleccionado == null || empleadoSeleccionado == null || fechaTexto.isEmpty() || horaTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios. Seleccione el vehículo que ingresa, "
                    + "el empleado que lo estaciona, en qué fecha y a qué hora.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato de hora HH:MM (24 horas)
        if (!horaTexto.matches("([01]\\d|2[0-3]):[0-5]\\d")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de hora inválido. Use HH:MM (24 hs)", "Atención", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato de fecha dd/MM/yyyy (opcional)
        if (!fechaTexto.matches("\\d{2}/\\d{2}/\\d{4}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use DD/MM/AAAA", "Atención", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Verificar si el vehículo ya está en el parking
        if (modelo.vehiculoEstaEnParking(vehiculoSeleccionado)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ese vehículo ya está dentro del parking.", "Información", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Registrar la entrada del vehículo
        modelo.registrarEntradaVehiculo(vehiculoSeleccionado, empleadoSeleccionado, fechaTexto, horaTexto, notas);

        javax.swing.JOptionPane.showMessageDialog(this, "Vehículo ingresado al parking correctamente.");

        cargarListas();
        listaVehiculosEntrada.clearSelection();
        listaEmpleadosEntrada.clearSelection();
        lblFechaEntrada.setText("");
        lblHoraEntrada.setText("");
        txtAreaNotasEntrada.setText("");

        System.out.println("Historial de Entradas:");
        for (EntradaVehiculo entrada : modelo.getHistorialEntradas()) {
            System.out.println(" - " + entrada);
        }
    }//GEN-LAST:event_btnEntradaVehiculoActionPerformed

