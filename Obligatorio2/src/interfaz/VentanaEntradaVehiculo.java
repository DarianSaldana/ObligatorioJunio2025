    private void cargarListas() {

        // Vehículos filtrando los que ya estan en el parking
        DefaultListModel modeloVehiculos = new DefaultListModel();
        for (Vehiculo v : modelo.getListaVehiculos()) {
            if (!modelo.vehiculoEstaEnParking(v)) {
                modeloVehiculos.addElement(v);
            }
        }
        listaVehiculosEntrada.setModel(modeloVehiculos);

        // Empleados
        DefaultListModel modeloEmpleados = new DefaultListModel();
        for (Empleado e : modelo.getListaEmpleados()) {
            modeloEmpleados.addElement(e);
        }
        listaEmpleadosEntrada.setModel(modeloEmpleados);

    }

