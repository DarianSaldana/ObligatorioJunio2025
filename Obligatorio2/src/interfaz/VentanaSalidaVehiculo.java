    private void cargarListas() {

        DefaultListModel modeloEntradas = new DefaultListModel();
        for (EntradaVehiculo entrada : modelo.getHistorialEntradas()) {
            if (!entrada.estaFinalizada()) {
                modeloEntradas.addElement(entrada);
            }
        }
        listaIngresosSalidaVehiculo.setModel(modeloEntradas);

        // Empleados
        DefaultListModel modeloEmpleados = new DefaultListModel();
        for (Empleado e : modelo.getListaEmpleados()) {
            modeloEmpleados.addElement(e);
        }
        listaEmpleadosSalida.setModel(modeloEmpleados);

    }

