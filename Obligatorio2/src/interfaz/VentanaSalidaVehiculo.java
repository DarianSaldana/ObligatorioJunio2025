    private void btnSalidaVehiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalidaVehiculoActionPerformed
        EntradaVehiculo entradaSeleccionada = (EntradaVehiculo) listaIngresosSalidaVehiculo.getSelectedValue();
        Empleado empleadoSalida = (Empleado) listaEmpleadosSalida.getSelectedValue();
        String fechaSalidaTexto = lblFechaSalida.getText().trim();
        String horaSalidaTexto = lblHoraSalida.getText().trim();
        String comentario = txtAreaComentariosSalida.getText().trim();

        if (entradaSeleccionada == null || empleadoSalida == null || fechaSalidaTexto.isEmpty() || horaSalidaTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato hora
        if (!horaSalidaTexto.matches("([01]\\d|2[0-3]):[0-5]\\d")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de hora inválido. Use HH:MM (24 hs)", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato fecha
        if (!fechaSalidaTexto.matches("\\d{2}/\\d{2}/\\d{4}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use DD/MM/AAAA", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Parsear fecha y hora de entrada y salida
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm");
        LocalDateTime fechaHoraEntrada = LocalDateTime.parse(entradaSeleccionada.getFecha() + " " + entradaSeleccionada.getHora(), formatter);
        LocalDateTime fechaHoraSalida;

        try {
            fechaHoraSalida = LocalDateTime.parse(fechaSalidaTexto + " " + horaSalidaTexto, formatter);
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo interpretar fecha y hora de salida.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!fechaHoraSalida.isAfter(fechaHoraEntrada)) {
            javax.swing.JOptionPane.showMessageDialog(this, "La salida debe ser posterior a la entrada.", "Atención", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Calcular duración
        Duration duracion = Duration.between(fechaHoraEntrada, fechaHoraSalida);
        long horas = duracion.toHours();
        long minutos = duracion.toMinutes() % 60;

        // Crear salida
        Vehiculo vehiculo = entradaSeleccionada.getVehiculo();
        SalidaVehiculo nuevaSalida = new SalidaVehiculo(vehiculo, empleadoSalida, fechaSalidaTexto, horaSalidaTexto, comentario);
        modelo.registrarSalidaVehiculo(entradaSeleccionada, nuevaSalida); // Esto lo implementamos ahora

        boolean tieneContrato = modelo.vehiculoTieneContrato(vehiculo);
        String infoContrato = tieneContrato ? "Este vehículo tiene contrato." : "Este vehículo no tiene contrato.";

        String mensaje = String.format("Salida registrada correctamente.\nTiempo en el parking: %d horas y %d minutos.\n%s", horas, minutos, infoContrato);
        javax.swing.JOptionPane.showMessageDialog(this, mensaje, "Salida registrada", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        cargarListas();
        listaIngresosSalidaVehiculo.clearSelection();
        listaEmpleadosSalida.clearSelection();
        lblFechaSalida.setText("");
        lblHoraSalida.setText("");
        txtAreaComentariosSalida.setText("");

        System.out.println("Historial de Salidas:");
        for (SalidaVehiculo salida : modelo.getHistorialSalidas()) {
            System.out.println(" - " + salida);
        }
    }//GEN-LAST:event_btnSalidaVehiculoActionPerformed

