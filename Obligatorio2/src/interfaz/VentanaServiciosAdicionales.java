    private void btnRegistrarServicioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarServicioActionPerformed
        Vehiculo vehiculoSeleccionado = (Vehiculo) listaVehiculosServicios.getSelectedValue();
        Empleado empleadoSeleccionado = (Empleado) listaEmpleadosServicios.getSelectedValue();
        String tipoServicio = (String) selectServicios.getSelectedItem();
        String fechaTexto = lblFechaServicio.getText().trim();
        String horaTexto = lblHoraServicio.getText().trim();
        String costoTexto = lblCostoServicioAdicional.getText().trim();

        if (vehiculoSeleccionado == null || empleadoSeleccionado == null
                || fechaTexto.isEmpty() || horaTexto.isEmpty() || costoTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios. Seleccione el vehículo, el empleado, la fecha, hora y costo del servicio.",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato de hora HH:MM (24 hs)
        if (!horaTexto.matches("([01]\\d|2[0-3]):[0-5]\\d")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de hora inválido. Use HH:MM (24 hs).",
                    "Atención", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar formato de fecha DD/MM/AAAA
        if (!fechaTexto.matches("\\d{2}/\\d{2}/\\d{4}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Formato de fecha inválido. Use DD/MM/AAAA.",
                    "Atención", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar costo numérico positivo
        double costo;
        try {
            costo = Double.parseDouble(costoTexto);
            if (costo < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El costo debe ser un número positivo.",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Crear y registrar el servicio
        ServicioAdicional nuevo = new ServicioAdicional(tipoServicio, fechaTexto, horaTexto, vehiculoSeleccionado, empleadoSeleccionado, costo);
        modelo.registrarServicioAdicional(nuevo);

        javax.swing.JOptionPane.showMessageDialog(this, "Servicio registrado correctamente.");

        // Actualizar lista de servicios
        DefaultListModel<ServicioAdicional> modeloServicios = new DefaultListModel<>();
        for (ServicioAdicional s : modelo.getServiciosAdicionales()) {
            modeloServicios.addElement(s);
        }
        listaServiciosExistentes.setModel(modeloServicios);

        // Limpiar campos
        listaVehiculosServicios.clearSelection();
        listaEmpleadosServicios.clearSelection();
        lblFechaServicio.setText("");
        lblHoraServicio.setText("");
        lblCostoServicioAdicional.setText("");
        selectServicios.setSelectedIndex(0);
    }//GEN-LAST:event_btnRegistrarServicioActionPerformed

    private void listaVehiculosServiciosValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaVehiculosServiciosValueChanged
        if (!evt.getValueIsAdjusting()) {
            Vehiculo vehiculoSeleccionado = (Vehiculo) listaServiciosExistentes.getSelectedValue();
            if (vehiculoSeleccionado != null && modelo.vehiculoTieneContrato(vehiculoSeleccionado)) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "El vehículo seleccionado posee un contrato.",
                        "Aviso",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_listaVehiculosServiciosValueChanged

