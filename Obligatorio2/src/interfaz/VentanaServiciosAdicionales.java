    private void cargarListas() {
        // Vehículos activos en el estacionamiento
        DefaultListModel<Vehiculo> modeloVehiculos = new DefaultListModel<>();
        for (EntradaVehiculo entrada : modelo.getHistorialEntradas()) {
            if (!entrada.estaFinalizada()) {
                modeloVehiculos.addElement(entrada.getVehiculo());
            }
        }
        listaVehiculosServicios.setModel(modeloVehiculos);

        // Empleados
        DefaultListModel<Empleado> modeloEmpleados = new DefaultListModel<>();
        for (Empleado e : modelo.getListaEmpleados()) {
            modeloEmpleados.addElement(e);
        }
        listaEmpleadosServicios.setModel(modeloEmpleados);

        // Tipos de servicio
        selectServicios.setModel(new javax.swing.DefaultComboBoxModel<>(new String[]{
            "Lavado", "Cambio de rueda", "Limpieza de tapizado", "Cambio de luces", "Otro"
        }));

        // Servicios registrados
        DefaultListModel<ServicioAdicional> modeloServicios = new DefaultListModel<>();
        for (ServicioAdicional s : modelo.getServiciosAdicionales()) {
            modeloServicios.addElement(s);
        }
        listaServiciosExistentes.setModel(modeloServicios);
    }

