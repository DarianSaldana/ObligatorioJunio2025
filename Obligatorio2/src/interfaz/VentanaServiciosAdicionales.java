    private void listaServiciosExistentesValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_listaServiciosExistentesValueChanged
        if (!evt.getValueIsAdjusting()) {
            ServicioAdicional servicioSeleccionado = (ServicioAdicional) listaServiciosExistentes.getSelectedValue();
            if (servicioSeleccionado != null) {
                String mensaje = "Servicio: " + servicioSeleccionado.getTipoServicio()
                        + "\nFecha: " + servicioSeleccionado.getFecha()
                        + "\nHora: " + servicioSeleccionado.getHora()
                        + "\nVehículo: " + servicioSeleccionado.getVehiculo().getMatricula() + " " + servicioSeleccionado.getVehiculo().getMarca()
                        + "\nEmpleado: " + servicioSeleccionado.getEmpleado().getNombre()
                        + "\nCosto: $" + servicioSeleccionado.getCosto();

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        mensaje,
                        "Detalle del Servicio",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_listaServiciosExistentesValueChanged

